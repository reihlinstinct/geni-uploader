def upload_opt(command: str, flag: str) -> Opt:
    """The spec option for an upload command; KeyError names the gap."""
    for opt in UPLOAD_COMMANDS[command].options:
        if opt.flag == flag:
            return opt
    raise KeyError(f"cli_spec: {command} has no option {flag}")


