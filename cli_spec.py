class Opt(NamedTuple):
    """One command-line option."""

    flag: str
    metavar: str | None
    help: str


class Command(NamedTuple):
    """One shipped command or mode."""

    name: str
    summary: str
    description: tuple[str, ...]
    options: tuple[Opt, ...] = ()
    examples: tuple[tuple[str, str], ...] = ()


