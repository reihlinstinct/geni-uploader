"""Canonical definition of the shipped geni-uploader command line (issue #515).

Single source of truth feeding both:

- the short explanations printed by ``--help`` (``geni_upload.py`` and
  ``source_details.py`` import these strings when they build their parsers), and
- the Linux man pages generated by ``tools/build_man_pages.py`` into
  ``man/man1/`` and installed by ``tools/install_man_pages.sh``.

``tests/test_cli_docs.py`` proves the shipped ``--help`` output and the
committed man pages never drift from this file. Edit command text here only.

Only shipped, user-facing commands belong here; internal development scripts
are not part of the command surface. No personal data, real names, profile
IDs or tokens: use invented examples only.
"""

from __future__ import annotations

from typing import NamedTuple

