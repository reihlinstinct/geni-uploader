"""Generate the Linux man pages from cli_spec.py (issue #515).

The pages are generated, not hand-written: edit cli_spec.py and re-run.

Usage:
  python tools/build_man_pages.py                  # regenerate man/man1/*.1 in place
  python tools/build_man_pages.py --check          # exit 1 if committed pages are stale
  python tools/build_man_pages.py --dir DIR        # write/compare against DIR instead
  python tools/build_man_pages.py --tarball OUT.tar.gz   # distributable man package

Standard library only. No network.
"""

from __future__ import annotations

import argparse
import gzip
import io
import sys
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import cli_spec

DEFAULT_DIR = ROOT / "man" / "man1"
HEADER_COMMENT = '.\\" Generated by tools/build_man_pages.py from cli_spec.py; do not edit.'


def esc(text: str) -> str:
    """Escape a text fragment for roff."""
    return text.replace("\\", r"\e").replace("-", r"\-")


def text_line(text: str) -> str:
    """A free-text roff line: a leading . or ' would be read as a request."""
    if text[:1] in (".", "'"):
        return "\\&" + esc(text)
    return esc(text)


def page_name(*parts: str) -> str:
    return "-".join((cli_spec.PROGRAM, *parts)) + ".1"


def th(title: str) -> list[str]:
    return [
        HEADER_COMMENT,
        (f'.TH "{esc(title).upper()}" "1" "{cli_spec.MAN_DATE}" '
         f'"{cli_spec.PROGRAM} {cli_spec.VERSION}" "{cli_spec.MANUAL}"'),
    ]


def name_section(page_stem: str, summary: str) -> list[str]:
    return [".SH NAME", f"{esc(page_stem)} \\- {esc(summary)}"]


def _synopsis_opt(opt: cli_spec.Opt, required: bool) -> str:
    flag = esc(opt.flag)
    if opt.metavar:
        if required:
            return f'.BI "{flag} " "{opt.metavar}"'
        return f'.BI "[{flag} " "{opt.metavar}]"'
    return f".B [{flag}]"


def synopsis_section(cmd: cli_spec.Command, display: str,
                     required: tuple[str, ...]) -> list[str]:
    """display is the full invocation prefix, e.g. 'geni-uploader plan'."""
    lines = [".SH SYNOPSIS", f".B {esc(display)}"]
    for opt in cmd.options:
        lines.append(_synopsis_opt(opt, opt.flag in required))
    return lines


def options_section(cmd: cli_spec.Command, required: tuple[str, ...],
                    include_token_file: bool) -> list[str]:
    lines = [".SH OPTIONS"]
    options = list(cmd.options)
    if include_token_file:
        options.insert(0, cli_spec.TOKEN_FILE)
    for opt in options:
        lines.append(".TP")
        flag = esc(opt.flag)
        if opt.metavar:
            lines.append(f'.BI "{flag} " "{opt.metavar}"')
        else:
            lines.append(f".B {flag}")
        suffix = " (required)" if opt.flag in required else ""
        lines.append(text_line(opt.help + suffix))
    lines.append(".TP")
    lines.append(".B \\-\\-help")
    lines.append("Show a short summary and the option list, then exit.")
    return lines


def description_section(paragraphs: tuple[str, ...]) -> list[str]:
    lines = [".SH DESCRIPTION", text_line(paragraphs[0])]
    for para in paragraphs[1:]:
        lines.append(".PP")
        lines.append(text_line(para))
    return lines


def examples_section(examples: tuple[tuple[str, str], ...]) -> list[str]:
    if not examples:
        return []
    lines = [".SH EXAMPLES"]
    for invocation, explanation in examples:
        lines.append(".TP")
        lines.append(f".B {esc(invocation)}")
        lines.append(text_line(explanation))
    return lines


def exit_status_section() -> list[str]:
    lines = [".SH EXIT STATUS"]
    for code, meaning in cli_spec.EXIT_STATUS:
        lines.append(".TP")
        lines.append(f".B {code}")
        lines.append(text_line(meaning))
    return lines


def _see_also(*refs: str) -> list[str]:
    lines = [".SH SEE ALSO"]
    rendered = [f".BR {esc(ref)} (1)" for ref in refs]
    chunks = [rendered[i:i + 2] for i in range(0, len(rendered), 2)]
    for index, chunk in enumerate(chunks):
        suffix = "," if index < len(chunks) - 1 else "."
        lines.append(", ".join(chunk) + suffix)
    return lines


def render_command(cmd: cli_spec.Command) -> str:
    """One page per shipped upload subcommand, git-style."""
    stem = f"{cli_spec.PROGRAM}-{cmd.name}"
    required = tuple(
        o.flag for o in cmd.options
        if o.flag in ("--manifest", "--client-id"))
    lines = th(stem)
    lines += name_section(stem, cmd.summary)
    lines += synopsis_section(cmd, f"{cli_spec.PROGRAM} {cmd.name}", required)
    lines += description_section(cmd.description)
    lines += options_section(cmd, required, include_token_file=True)
    lines += examples_section(cmd.examples)
    lines += exit_status_section()
    lines += _see_also(cli_spec.PROGRAM)
    return "\n".join(lines) + "\n"


def render_details_mode(mode: str, cmd: cli_spec.Command) -> str:
    """One page per shipped details-* mode."""
    stem = f"{cli_spec.PROGRAM}-details-{mode}"
    required_by_mode = {
        "repair": ("--manifest", "--confirm", "--state"),
        "snapshot": ("--manifest", "--output"),
    }
    required = required_by_mode.get(mode, ("--manifest",))
    lines = th(stem)
    lines += name_section(stem, cmd.summary)
    lines += synopsis_section(cmd, f"{cli_spec.PROGRAM} details-{mode}", required)
    lines += description_section(cmd.description)
    lines += options_section(cmd, required, include_token_file=False)
    lines += exit_status_section()
    lines += _see_also(cli_spec.PROGRAM)
    return "\n".join(lines) + "\n"


def render_overview() -> str:
    stem = cli_spec.PROGRAM
    lines = th(stem)
    lines += name_section(stem, "user-run uploader for Geni source documents and photos")
    lines += [".SH SYNOPSIS",
              (f".B {esc(stem)} "
               f"[{esc(cli_spec.TOKEN_FILE.flag)} {cli_spec.TOKEN_FILE.metavar}] "
               "COMMAND [OPTIONS]")]
    lines += description_section(cli_spec.OVERVIEW_DESCRIPTION)
    lines.append(".SH COMMANDS")
    for cmd in cli_spec.UPLOAD_COMMANDS.values():
        lines.append(".TP")
        lines.append(f".B {esc(cmd.name)}")
        lines.append(text_line(cmd.summary))
    for mode, cmd in cli_spec.DETAILS_COMMANDS.items():
        lines.append(".TP")
        lines.append(f".B details-{esc(mode)}")
        lines.append(text_line(cmd.summary))
    lines.append(".SH ENVIRONMENT")
    for var, meaning in cli_spec.ENVIRONMENT:
        lines.append(".TP")
        lines.append(f".B {esc(var)}")
        lines.append(text_line(meaning))
    lines.append(".SH FILES")
    for path, meaning in cli_spec.FILES:
        lines.append(".TP")
        lines.append(f".B {esc(path)}")
        lines.append(text_line(meaning))
    lines += exit_status_section()
    refs = [f"{cli_spec.PROGRAM}-{name}" for name in cli_spec.UPLOAD_COMMANDS]
    refs += [f"{cli_spec.PROGRAM}-details-{mode}" for mode in cli_spec.DETAILS_COMMANDS]
    lines += _see_also(*refs)
    return "\n".join(lines) + "\n"


def render_all() -> dict[str, str]:
    """Every generated page: file name -> roff text."""
    pages = {page_name(): render_overview()}
    for cmd in cli_spec.UPLOAD_COMMANDS.values():
        pages[page_name(cmd.name)] = render_command(cmd)
    for mode, cmd in cli_spec.DETAILS_COMMANDS.items():
        pages[page_name("details", mode)] = render_details_mode(mode, cmd)
    return pages


def write_pages(pages: dict[str, str], target: Path) -> list[str]:
    """Write pages, removing stale generated ones. Returns notes."""
    target.mkdir(parents=True, exist_ok=True)
    notes = []
    stale = sorted(p.name for p in target.glob("*.1") if p.name not in pages)
    for name in stale:
        (target / name).unlink()
        notes.append(f"removed stale page {name}")
    for name, text in sorted(pages.items()):
        (target / name).write_text(text, encoding="utf-8")
    notes.append(f"wrote {len(pages)} pages to {target}")
    return notes


def check_pages(pages: dict[str, str], target: Path) -> list[str]:
    """Differences between committed pages and a fresh render; empty is clean."""
    problems = []
    on_disk = {p.name: p.read_text(encoding="utf-8") for p in target.glob("*.1")}
    for name in sorted(set(on_disk) - set(pages)):
        problems.append(f"{name}: committed page has no generator source")
    for name in sorted(set(pages) - set(on_disk)):
        problems.append(f"{name}: not generated (run tools/build_man_pages.py)")
    for name in sorted(set(pages) & set(on_disk)):
        if on_disk[name] != pages[name]:
            problems.append(f"{name}: stale (run tools/build_man_pages.py)")
    return problems


def write_tarball(pages: dict[str, str], out: Path) -> str:
    """A deterministic .tar.gz man package: geni-uploader-<VERSION>/man/man1/*.1."""
    base = f"{cli_spec.PROGRAM}-{cli_spec.VERSION}/man/man1"
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("wb") as raw, \
            gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=0) as gz, \
            tarfile.open(fileobj=gz, mode="w") as tar:
        for name, text in sorted(pages.items()):
            data = text.encode("utf-8")
            info = tarfile.TarInfo(f"{base}/{name}")
            info.size = len(data)
            info.mtime = 0
            info.mode = 0o644
            tar.addfile(info, io.BytesIO(data))
    return f"wrote {out} ({len(pages)} pages)"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="only compare committed pages against a fresh render")
    parser.add_argument("--dir", type=Path, default=DEFAULT_DIR,
                        help=f"target directory (default: {DEFAULT_DIR})")
    parser.add_argument("--tarball", type=Path, default=None,
                        help="also write a distributable .tar.gz man package here")
    args = parser.parse_args(argv)
    pages = render_all()
    if args.check:
        problems = check_pages(pages, args.dir)
        for problem in problems:
            print(f"error: {problem}", file=sys.stderr)
        if problems:
            return 1
        print(f"man pages in {args.dir} are up to date ({len(pages)} pages)")
        return 0
    for note in write_pages(pages, args.dir):
        print(note)
    if args.tarball:
        print(write_tarball(pages, args.tarball))
    return 0


if __name__ == "__main__":
    sys.exit(main())
